const { _electron: electron } = require('playwright');
const { expect } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { execFileSync } = require('node:child_process');
const { campaign, stock } = require('./helpers/business.cjs');
const { openDay, newGame, purchaseUpgrade, setPlan, buy } = require('../.test-build/simulation/game.js');
const { encodeSave } = require('../.test-build/simulation/save.js');
const { beginStreetDay, finishStreetDay } = require('../.test-build/simulation/street-day.js');
const executable = process.env.LEMONADE_DESKTOP_EXE;
if (process.platform !== 'win32' || !executable || !fs.existsSync(executable)) throw new Error('Set LEMONADE_DESKTOP_EXE to the Windows executable.');
const base = fs.mkdtempSync(path.join(os.tmpdir(), 'lemonade-management-'));
const env = { ...process.env, LOCALAPPDATA: base, APPDATA: path.join(base, 'Roaming') }; delete env.ELECTRON_RUN_AS_NODE;
const save = path.join(base, 'Lemonade Tycoon', 'save.json');
const read = () => { try { return JSON.parse(fs.readFileSync(save, 'utf8')); } catch { return null; } };
let app;
async function launch() { app = await electron.launch({ executablePath: path.resolve(executable), env }); const page = await app.firstWindow(); await expect(page.locator('canvas')).toBeVisible(); return page; }
async function close() { const closed = app.waitForEvent('close'); await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close()); await closed; app = null; }
(async () => {
    try {
        let page = await launch();
        let lowCash = purchaseUpgrade(newGame(), 'iceMaker');
        lowCash = setPlan(lowCash, { price: 175, recipe: { lemon: 1, sugar: 1, ice: 1 } });
        lowCash = buy(buy(buy(lowCash, 'lemon', 343), 'sugar', 2), 'cup', 8);
        assert.equal(lowCash.cash, 0);
        await page.locator('#save-file').setInputFiles({ name: 'low-cash.json', mimeType: 'application/json', buffer: Buffer.from(encodeSave(lowCash, [])) });
        await expect(page.locator('#save-status')).toContainText('Imported');
        await page.locator('[data-page=marketing]').click();
        await expect(page.locator('#management-bill')).toContainText('Opening bill $0.00');
        await page.locator('#open').click();
        await expect.poll(() => read()?.state.business?.paid).toBe(true);
        const freeCheckpoint = read();
        assert.equal(freeCheckpoint.state.cash, 0);
        assert.equal(freeCheckpoint.state.freeIce, 60);
        assert.equal(freeCheckpoint.state.daily.purchases, lowCash.daily.purchases);
        await close(); page = await launch();
        assert.deepEqual(read(), freeCheckpoint);
        await page.locator('#open').click(); await page.locator('#skip').click();
        await expect.poll(() => read()?.state.phase).toBe('results');
        assert.deepEqual(read().state, finishStreetDay(beginStreetDay(openDay(freeCheckpoint.state))).day.game);
        const earned = campaign(); earned.state = stock(earned.state);
        await page.locator('#save-file').setInputFiles({ name: 'earned.json', mimeType: 'application/json', buffer: Buffer.from(encodeSave(earned.state, earned.history)) });
        await expect(page.locator('#save-status')).toContainText('Imported');
        await page.locator('[data-page=upgrades]').click();
        for (const id of ['blender', 'refrigerator', 'iceMaker']) await page.locator(`[data-upgrade=${id}]`).click();
        await page.locator('[data-page=staff]').click(); await page.locator('[data-staff=server]').click();
        await page.locator('[data-page=marketing]').click(); await page.locator('[data-advertising=radio]').click();
        await page.locator('#help-open').click(); await page.locator('#mute-audio').check(); await page.locator('#help-close').click();
        await close(); page = await launch();
        await expect.poll(() => read()?.state.management.advertising).toBe('radio');
        const prepared = read();
        assert.equal(prepared.state.daily.capital, 3500);
        await page.locator('#open').click(); await expect(page.locator('#selling')).toBeVisible();
        await expect.poll(() => read()?.state.business?.paid).toBe(true);
        const paid = read();
        assert.equal(paid.state.daily.wages, 250); assert.equal(paid.state.daily.advertising, 450);
        assert.equal(paid.state.stock.ice, prepared.state.stock.ice + 60);
        assert.equal(paid.state.freeIce, prepared.state.freeIce + 60);
        assert.equal(paid.state.daily.purchases, prepared.state.daily.purchases);
        const expected = finishStreetDay(beginStreetDay(openDay(paid.state))).day.game;
        await expect.poll(async () => Number(await page.locator('#sold').textContent())).toBeGreaterThan(0);
        const closed = app.waitForEvent('close'); execFileSync('taskkill', ['/PID', String(app.process().pid), '/T', '/F']); await closed; app = null;
        page = await launch(); assert.deepEqual(read(), paid);
        await page.locator('[data-page=staff]').click(); await expect(page.locator('[data-staff=none]')).toBeDisabled();
        await page.locator('#open').click(); await page.locator('#skip').click();
        await expect.poll(() => read()?.state.phase).toBe('results'); assert.deepEqual(read().state, expected);
        await close(); page = await launch(); assert.deepEqual(read().state, expected);
        await page.locator('#help-open').click(); await expect(page.locator('#mute-audio')).toBeChecked();
        const diagnostic = await page.evaluate(() => window.desktopApp.diagnostics());
        assert.equal(diagnostic.version, '0.2.0-alpha.1'); assert.match(diagnostic.events, /startup/);
        assert.ok(!diagnostic.events.includes(base));
        await page.locator('#fullscreen').click();
        await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(true);
        await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isFullScreen())).toBe(true);
        await page.locator('#fullscreen').click();
        await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(false);
        const quit = app.waitForEvent('close'); await page.locator('#quit-game').click(); await quit; app = null;
        assert.deepEqual(read().state, expected);
        console.log('Windows management: equipment, wage/ad/ice costs, forced replay, results, mute, diagnostics, fullscreen and Save and quit PASS.');
    } finally { if (app) await app.close().catch(() => {}); fs.rmSync(base, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
